/**
 * Единый список ролей пользователей платформы.
 *
 * Значения enum совпадают со строками в БД/API-контрактах, поэтому менять их
 * нужно только вместе с миграциями и синхронизацией frontend-типов.
 */
export enum UserRole {
  /** Полный доступ ко всем организациям и настройкам платформы. */
  SUPER_ADMIN = 'superAdmin',
  /** Администратор одной или нескольких организаций. */
  ADMIN = 'admin',
  /** Staff-роль для управления контентом/меню без полного admin-доступа. */
  MODERATOR = 'moderator',
  /** Staff-роль для операционных сценариев. */
  OPERATOR = 'operator',
  /** Обычный клиент публичного web-приложения. */
  USER = 'user',
}
