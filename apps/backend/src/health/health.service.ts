import { Injectable } from '@nestjs/common';

/**
 * Сервис health-check'а приложения.
 *
 * Сейчас проверка минимальная и подтверждает только, что NestJS процесс
 * отвечает на HTTP-запросы. При необходимости сюда можно добавить проверки БД,
 * очередей, SMTP и внешних интеграций.
 */
@Injectable()
export class HealthService {
  /**
   * Возвращает машинный статус для мониторинга.
   *
   * `ok` намеренно остается латиницей: это стабильное техническое значение,
   * удобное для Docker/CI/health-probes.
   */
  getHealth() {
    return { status: 'ok' };
  }
}
